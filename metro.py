def build_metro() -> Graph:
    graph = Graph()
    for stations, times in LINES:
        for station in stations:
            graph.add_vertex(station)
        for i in range(len(stations) - 1):
            graph.add_edge(stations[i], stations[i + 1], times[i])

    # замыкаем кольцевую линию
    graph.add_edge(LINES[1][0][-1], LINES[1][0][0], 3.0)
    for first, second, time in TRANSFERS:
        graph.add_edge(first, second, time)
    return graph
